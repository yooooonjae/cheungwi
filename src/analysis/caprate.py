"""Cap Rate — 시장 소득수익률 벤치마크와 실거래 역산의 이중 검증.

cap rate 는 "이 건물의 1년 소득이 가격의 몇 %인가"이고, 소득을 가치로
바꾸는 나눗셈의 분모다. 분모가 흔들리면 감정가가 그대로 흔들린다. 그래서
이 모듈은 cap 을 **두 경로로** 만든다.

    benchmark : R-ONE 분기 소득수익률(%) 최근 4분기 합 → 시장 벤치마크
    implied   : 추정 NOI ÷ 실제 거래가 → 그 거래 한 건이 함의한 cap

둘은 서로 검산이다. 벤치마크가 4.0% 인데 역산이 3.2% 라면 시장이 그 건물에
프리미엄을 준 것이거나 우리 NOI 추정이 낮은 것이다 — 어느 쪽인지 이 모듈은
모른다. **두 값을 평균해 하나로 뭉개지 말고 괴리를 그대로 공개하라.**

전부 순수 함수다 — I/O 도 전역 상태도 없다. 표준 라이브러리(`math`)만 쓴다.

규약이 셋 있다.

1. **입력 소득수익률은 %, 반환 cap 은 소수다.** R-ONE 이 0.94(=0.94%)로 주는
   분기 수익률을 그대로 넣으면 0.0381(=3.81%)이 나온다. 100배 차이라
   뒤집어 넣으면 결과가 100배 또는 100분의 1 로 어긋난다. 나눗셈(÷100)은
   이 안에서 한다.
2. **최근 4분기는 리스트의 뒤 넷이다.** 입력은 오래된 → 최신 순서여야 한다
   (R-ONE 수집기가 `yq` 오름차순으로 저장하므로 그대로 넘기면 된다).
   4분기 합으로 연환산하는 것은 R-ONE 수익률이 **분기 수익률**이라 곱셈
   복리가 아니라 단순 합이 관행이기 때문이다(분기 값이 1% 안팎이라 복리와
   차이가 0.01%p 수준).
3. **cap 은 0.02~0.12(양끝 포함) 안이어야 한다.** 밖이면 값을 돌려주지 않고
   `RuntimeError` 를 던진다. 서울 오피스 cap 의 실측 범위를 넉넉히 감싼
   값이라, 여기를 벗어났다면 cap 이 틀린 것이 아니라 단위(%↔소수)나
   입력(NOI·가격의 자릿수)이 틀린 것이다. 게이트는 `benchmark` 의 산출과
   `implied` 의 산출 양쪽에 걸고, 소비 쪽인 `value.appraise` 는 같은 상수를
   임포트해 인자에 건다 — 한 곳만 막으면 다른 경로로 새어 나간다.

NaN·무한대는 도메인 검사가 아니라 별도 가드로 막는다. 크기 비교가 전부
False 라 게이트를 조용히 통과하는데, NaN cap 으로 나눈 감정가는 NaN 이고
그것은 정상 float 처럼 생겨서 하류(대출·IRR)까지 그대로 흘러간다.

오류 유형은 둘을 구분한다. 값이 물리적으로 말이 안 되면(가격 0 이하, 음수
소득수익률, NaN·inf, 4분기 미만) `ValueError` 로 "입력이 틀렸다"고 하고,
값 자체는 말이 되는데 cap 이 범위 밖이면 `RuntimeError` 로 "단위를
의심하라"고 한다.
"""

import math

# 물리 게이트 경계(소수 연율, 양끝 포함). 서울 오피스 cap 의 실측 범위를
# 넉넉히 감쌌다. `value` 가 이 상수를 임포트해 쓴다(단일 출처).
CAP_MIN = 0.02
CAP_MAX = 0.12

# 연환산에 쓰는 분기 수(R-ONE 소득수익률은 분기 값이다).
QUARTERS_PER_YEAR = 4

_PERCENT = 100.0


def _require_finite(x: float, what: str) -> None:
    """NaN·무한대를 입력 오류로 잡는다. 자기 자신과 다른 값은 NaN 뿐이다.

    NaN 은 크기 비교가 전부 False 라 게이트(`CAP_MIN <= cap <= CAP_MAX`)를
    통과하지 못하고 걸리기는 하지만, 그때 나오는 오류 유형이 "단위를
    의심하라"(RuntimeError)가 되어 원인을 잘못 짚는다. inf 는 가격처럼 상한
    검사가 없는 인자에서 그대로 지나가 cap 을 0 이나 inf 로 만든다.
    """
    if x != x:
        raise ValueError(f"{what} 값이 NaN 이다 — 검사를 조용히 통과하므로 막는다")
    if math.isinf(x):
        raise ValueError(f"{what} 값이 무한대다 — 검사를 조용히 통과하므로 막는다")


def _gate_cap(cap: float, what: str) -> float:
    """cap 이 물리 범위(0.02~0.12) 안인지 확인하고 그대로 돌려준다.

    밖이면 멈춘다. 부호·NaN 은 부르는 쪽이 먼저 `ValueError` 로 걸러 여기
    오지 않는다 — 여기 걸리는 값은 "cap 으로는 말이 되는데 자릿수가 이상한"
    값뿐이라 메시지가 단위를 짚는다.
    """
    if not CAP_MIN <= cap <= CAP_MAX:
        raise RuntimeError(
            f"{what} {cap:.6f}(= {cap * _PERCENT:.4f}%)이 물리 범위"
            f"[{CAP_MIN}, {CAP_MAX}] 밖이다 — cap 이 아니라 단위(%↔소수)나 "
            "입력 자릿수를 의심하라. 이대로 두면 감정가가 배수로 어긋난 채 "
            "대출·IRR 까지 조용히 흘러간다"
        )
    return cap


def benchmark(income_yield_quarterly_pct: list[float]) -> dict:
    """R-ONE 분기 소득수익률(%)의 최근 4분기 합을 연환산 cap 벤치마크로.

    | 단계 | 산식                                | 예(G-CAP-001)                    |
    |------|-------------------------------------|----------------------------------|
    | 선택 | 리스트의 뒤 4개(최근 4분기)         | [0.94, 0.95, 0.96, 0.96]         |
    | 합   | Σ 분기 소득수익률(%)                | 0.94+0.95+0.96+0.96 = 3.81%      |
    | 환산 | ÷ 100 (% → 소수)                    | 0.0381                           |

    **단위 규약: 입력은 %, 반환은 소수다.** 0.94 는 0.94%(0.0094)를 뜻한다.
    R-ONE `regions[권역]["yield"][*]["income"]` 값을 그대로 넣으면 된다.
    소수(0.0094)를 넣으면 결과가 100분의 1 이 되어 게이트에 걸린다.

    **순서 규약: 오래된 → 최신.** 뒤에서 넷을 최근 4분기로 본다. 4분기보다
    짧으면 `ValueError` 다 — 세 분기만으로 연환산하면 4분의 3 짜리 cap 이
    나오는데 그 값도 게이트 안(2~12%)이라 조용히 통과하기 때문이다.

    **검사 범위: 합에는 뒤 4분기만 쓰지만 검사는 넘어온 계열 전체에 건다.**
    음수·NaN·inf 한 개는 그 분기 하나가 아니라 계열을 잘못 넣었다는 신호라
    앞쪽 분기에 있어도 `ValueError` 다. 뒤 넷만 보면 자본수익률 계열이라도
    최근 4분기가 우연히 양수이고 합이 게이트 안이면 새어 나간다.

    반환: `{"cap_income_based": 소수 cap, "quarters_used": [쓴 4개 %],
    "caveats": [...]}`. `caveats` 는 계약(두 키)에 더한 것이다 — 시장
    벤치마크를 개별 건물 cap 으로 인용하지 못하게 라벨을 붙여 보낸다.

    게이트: 결과 cap 이 0.02~0.12 밖이면 `RuntimeError`.
    """
    if len(income_yield_quarterly_pct) < QUARTERS_PER_YEAR:
        raise ValueError(
            f"연환산에는 최근 {QUARTERS_PER_YEAR}분기가 필요하다: "
            f"{len(income_yield_quarterly_pct)}개만 들어왔다"
        )
    # 검사는 넘어온 **계열 전체**에 건다. 합에 쓰는 것은 뒤 4분기뿐이지만,
    # 음수 한 개는 그 분기 하나가 아니라 계열을 잘못 넣었다는 신호이기
    # 때문이다. 뒤 넷만 보면 자본수익률 계열이라도 최근 4분기가 우연히
    # 양수이고 합이 게이트 안(예: 0.5+0.6+0.5+0.6 = 2.2%)이면 cap 0.022 로
    # 조용히 통과한다. 소득수익률은 정의상 음수가 없어 오탐 비용이 0 이다.
    for i, q in enumerate(income_yield_quarterly_pct):
        _require_finite(q, f"{i}번째 분기 소득수익률")
        if q < 0:
            raise ValueError(
                f"{i}번째 분기 소득수익률이 음수다: {q} — 소득수익률은 정의상 "
                "음수가 될 수 없다. 음수가 나올 수 있는 것은 자본수익률"
                "(capital)이므로 계열을 잘못 넣었는지 보라. 합에 쓰는 것은 뒤 "
                f"{QUARTERS_PER_YEAR}분기뿐이지만 검사는 계열 전체에 건다"
            )

    # 슬라이스가 새 리스트를 만든다 — 입력을 건드리지 않고, 반환한 리스트를
    # 부르는 쪽이 고쳐도 다음 호출이 오염되지 않는다.
    recent = income_yield_quarterly_pct[-QUARTERS_PER_YEAR:]

    cap = _gate_cap(math.fsum(recent) / _PERCENT, "소득수익률 벤치마크 cap")

    return {
        "cap_income_based": cap,
        "quarters_used": recent,
        "caveats": [
            "R-ONE 상업용부동산 임대동향조사의 **권역 평균** 소득수익률이다. "
            "개별 건물의 cap 이 아니라 그 권역 표본의 중심값이므로, 건물 한 "
            "동에 그대로 붙이면 입지·연식·임차인 구성의 차이가 지워진다.",
            "분기 수익률 4개를 단순 합으로 연환산했다(복리 아님). 분기 값이 "
            "1% 안팎이라 차이는 0.01%p 수준이지만 정의상 근사다.",
            "소득수익률은 R-ONE 표본의 평가 기준 순영업소득/자산가치이고, 이 "
            "엔진이 쓰는 NOI 정의(전용률·공실·미회수 opex 가정)와 산출 방식이 "
            "다르다. 벤치마크와 실거래 역산(implied)의 괴리를 평균으로 "
            "뭉개지 말고 그대로 공개하라.",
        ],
    }


def implied(noi_won_y: float, price_won: float) -> float:
    """실거래가가 함의한 cap = NOI ÷ 가격.

    | 예(G-IMP-001) | 산식                             | 값            |
    |---------------|----------------------------------|---------------|
    | NOI 121.125억 / 가격 2,700억 | 12,112,500,000 / 270,000,000,000 | 0.0448611111… |

    NOI 는 원/년, 가격은 원이다. 둘 다 이 엔진의 금액 규약(원)을 따르므로
    억·조 단위를 섞어 넣으면 자릿수가 어긋나 게이트에 걸린다.

    도메인: 가격은 양수, NOI 는 0 이상이며 둘 다 유한해야 한다. 밖이면
    `ValueError`. NOI 0(전관 공실)은 입력으로는 말이 되지만 역산 cap 이 0 이
    되어 게이트에 걸린다 — 그 거래는 소득으로 설명되지 않는다는 뜻이다.

    게이트: cap 이 0.02~0.12 밖이면 `RuntimeError`. 반환은 소수다(0.045 =
    4.5%). 이 값은 **거래 한 건**이 함의한 cap 이라 표본이 1 이다.
    `benchmark` 와 나란히 놓고 괴리를 보라.
    """
    _require_finite(noi_won_y, "NOI")
    if noi_won_y < 0:
        raise ValueError(f"NOI 는 음수일 수 없다: {noi_won_y}")
    _require_finite(price_won, "거래가격")
    if price_won <= 0:
        raise ValueError(f"거래가격은 양수여야 한다: {price_won}")

    return _gate_cap(noi_won_y / price_won, "실거래 역산 cap")
